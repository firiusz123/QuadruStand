#!/usr/bin/env bash
# Write a path-based .pth so Pyrefly (Cursor's Python language server) can
# resolve Isaac Lab. Runtime already finds those packages via setuptools
# import-hook .pth files; the type checker cannot execute those hooks.
#
# Discovers checkout paths from the current .venv (wherever Isaac Lab was
# cloned), so the same script works on another machine.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PYTHON="${ROOT}/.venv/bin/python"

if [[ ! -x "${PYTHON}" ]]; then
    echo "error: ${ROOT}/.venv not found. Create the environment first (README: Installation)." >&2
    exit 1
fi

"${PYTHON}" - <<'PY'
from __future__ import annotations

import re
import site
import sys
from pathlib import Path

PTH_NAME = "isaaclab_editable_paths.pth"
FINDER_GLOB = "__editable___*_finder.py"
PATH_RE = re.compile(r"'(/[^']+)'")

roots: list[str] = []
seen: set[str] = set()

for site_dir in map(Path, site.getsitepackages()):
    for finder in sorted(site_dir.glob(FINDER_GLOB)):
        if "isaaclab" not in finder.name:
            continue
        text = finder.read_text()
        start = text.find("MAPPING")
        if start < 0:
            continue
        end = text.find("}", start)
        for pkg_path in PATH_RE.findall(text[start:end]):
            root = str(Path(pkg_path).parent)
            if root not in seen and Path(root).is_dir():
                seen.add(root)
                roots.append(root)

if not roots:
    sys.exit(
        "error: no Isaac Lab editable installs found in .venv.\n"
        "Install Isaac Lab first (README: Installation, step 3)."
    )

header = (
    "# Generated by scripts/tools/configure_pyrefly.sh\n"
    "# Path-based shims so Pyrefly can resolve Isaac Lab editable installs.\n"
    "# Safe to delete; rerun the script to recreate.\n"
)
pth = Path(site.getsitepackages()[0]) / PTH_NAME
pth.write_text(header + "\n".join(roots) + "\n")
print(f"wrote {len(roots)} path(s) to {pth}")
for root in roots:
    print(f"  {root}")
PY
